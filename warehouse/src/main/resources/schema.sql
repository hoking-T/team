CREATE TABLE IF NOT EXISTS product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, unit VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS location (id BIGINT PRIMARY KEY, code VARCHAR(20) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS stock (
 product_id BIGINT NOT NULL REFERENCES product(id), location_id BIGINT NOT NULL REFERENCES location(id),
 quantity BIGINT NOT NULL DEFAULT 0 CHECK(quantity BETWEEN 0 AND 1000000000),
 PRIMARY KEY(product_id,location_id)
);
CREATE TABLE IF NOT EXISTS inbound (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES product(id), location_id BIGINT NOT NULL REFERENCES location(id),
 quantity BIGINT NOT NULL CHECK(quantity BETWEEN 1 AND 1000000), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS outbound_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES product(id), location_id BIGINT NOT NULL REFERENCES location(id),
 quantity BIGINT NOT NULL CHECK(quantity BETWEEN 1 AND 1000000),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SHIPPED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS shipment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES outbound_order(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('WAITING','TRANSIT','DELIVERED'))
);
CREATE TABLE IF NOT EXISTS tracking (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shipment_id BIGINT NOT NULL REFERENCES shipment(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('WAITING','TRANSIT','DELIVERED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(shipment_id,status)
);
CREATE TABLE IF NOT EXISTS event_log (
 event_id VARCHAR(36) PRIMARY KEY, event_type VARCHAR(40) NOT NULL, aggregate_id BIGINT NOT NULL,
 details VARCHAR(200) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_order_product ON outbound_order(product_id);
CREATE INDEX IF NOT EXISTS ix_inbound_product ON inbound(product_id);
CREATE INDEX IF NOT EXISTS ix_tracking_time ON tracking(shipment_id,created_at,id);
